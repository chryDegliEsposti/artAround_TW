// Autoscale the arbitrary x/y coordinates into the 500x500 canvas preserving aspect ratio
const transformDataForCanvas = (data, canvasSize = 500, padding = 40) => {
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  data.lines.forEach(line => line.points.forEach(pt => {
    if (pt.x < minX) minX = pt.x; if (pt.x > maxX) maxX = pt.x;
    if (pt.y < minY) minY = pt.y; if (pt.y > maxY) maxY = pt.y;
  }));
  data.pois.forEach(poi => {
    if (poi.position.x < minX) minX = poi.position.x; if (poi.position.x > maxX) maxX = poi.position.x;
    if (poi.position.y < minY) minY = poi.position.y; if (poi.position.y > maxY) maxY = poi.position.y;
  });

  if (minX === Infinity) return { scale: 1, offsetX: 0, offsetY: 0 };

  const width = Math.max(maxX - minX, 1);
  const height = Math.max(maxY - minY, 1);
  const drawArea = canvasSize - padding * 2;
  const scale = drawArea / Math.max(width, height);
  const offsetX = (canvasSize - (width * scale)) / 2 - minX * scale;
  const offsetY = (canvasSize - (height * scale)) / 2 - minY * scale;

  return { scale, offsetX, offsetY };
};

const { scale, offsetX, offsetY } = transformDataForCanvas(mockMuseumData);
const tx = (x) => x * scale + offsetX;
const ty = (y) => y * scale + offsetY;

