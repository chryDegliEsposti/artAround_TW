export default function NavigatorApp() {
  const { state } = useLocation();
  const navigate = useNavigate();
  const canvasRef = useRef(null);
  const { speak, pause, stop, seek, isSpeaking, currentTime, duration } = useSpeaker();

  const [items] = useState(mockTourItems);
  const [currentIndex, setCurrentIndex] = useState(0);
  const [isPlaying, setIsPlaying] = useState(false);
  const [showDescription, setShowDescription] = useState(false);
  const [showPopup, setShowPopup] = useState(false);
  const [showMoreMenu, setShowMoreMenu] = useState(false);
  const [isCameraActive, setIsCameraActive] = useState(false);
  const [aiResponse, setAiResponse] = useState(null);
  const [hasTriggeredCurrent, setHasTriggeredCurrent] = useState(false);

  // Pathfinding and Navigation States
  const [collisionGrid, setCollisionGrid] = useState(null);
  const [currentPath, setCurrentPath] = useState([]);
  const [mapZoom, setMapZoom] = useState(4.5); // Default significantly zoomed in for human-to-museum scale
  const moveIntervalRef = useRef(null);

  // Native Full-Screen Scale
  const [windowSize, setWindowSize] = useState({ w: window.innerWidth, h: window.innerHeight });

  useEffect(() => {
    const handleResize = () => setWindowSize({ w: window.innerWidth, h: window.innerHeight });
    window.addEventListener('resize', handleResize);
    return () => window.removeEventListener('resize', handleResize);
  }, []);

  // Camera and Panning state
  const [isTrackingUser, setIsTrackingUser] = useState(true);
  const [cameraPos, setCameraPos] = useState({ x: 250, y: 250 });
  const [isPanning, setIsPanning] = useState(false);
  const lastPanRef = useRef({ x: 0, y: 0 });

  // User simulated position (started near the first exhibit)
  const startPos = items.length > 0 ? { x: items[0].x, y: items[0].y + 40 } : { x: 250, y: 250 };
  const [userPos, setUserPos] = useState(startPos);

  const currentItem = items[currentIndex];

  useEffect(() => {
    setCollisionGrid(createCollisionGrid(mockMuseumData.lines, mockMuseumData.pois, tx, ty));
  }, []);

  useEffect(() => {
    if (collisionGrid && currentItem) {
      setCurrentPath(findPath(collisionGrid, userPos, { x: currentItem.x, y: currentItem.y }));
    }
  }, [userPos, currentItem, collisionGrid]);

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext('2d');

    // Clear background
    ctx.clearRect(0, 0, canvas.width, canvas.height);

    ctx.save(); // Save default context state
    ctx.lineCap = 'round';
    ctx.lineJoin = 'round';

    // Camera Transform System
    const cameraX = isTrackingUser ? userPos.x : cameraPos.x;
    const cameraY = isTrackingUser ? userPos.y : cameraPos.y;

    if (mapZoom > 1) {
      // 1. Move origin to canvas center
      ctx.translate(canvas.width / 2, canvas.height / 2);
      // 2. Scale up
      ctx.scale(mapZoom, mapZoom);
      // 3. Move origin back, offset by Camera Pos
      ctx.translate(-cameraX, -cameraY);
    }

    // Draw high-end grid background
    const gridSize = 100;
    ctx.beginPath();
    ctx.strokeStyle = '#f1f5f9';
    ctx.lineWidth = 1 / mapZoom;
    for (let x = -2000; x <= 4000; x += gridSize) {
      ctx.moveTo(x, -8000); ctx.lineTo(x, 2000);
    }
    for (let y = -8000; y <= 2000; y += gridSize) {
      ctx.moveTo(-2000, y); ctx.lineTo(4000, y);
    }
    ctx.stroke();

    // Draw Floor Fill based on external walls
    mockMuseumData.lines.filter(l => l.type === 'ext-wall').forEach(line => {
      ctx.beginPath();
      line.points.forEach((pt, i) => {
        const cx = tx(pt.x);
        const cy = ty(pt.y);
        if (i === 0) ctx.moveTo(cx, cy); else ctx.lineTo(cx, cy);
      });
      ctx.fillStyle = '#ffffff';
      ctx.fill();
    });

    // Draw lines (walls) from JSON
    mockMuseumData.lines.forEach(line => {
      ctx.beginPath();
      line.points.forEach((pt, i) => {
        const cx = tx(pt.x);
        const cy = ty(pt.y);
        if (i === 0) ctx.moveTo(cx, cy);
        else ctx.lineTo(cx, cy);
      });

      const isExt = line.type === 'ext-wall';
      ctx.strokeStyle = isExt ? '#1e293b' : '#94a3b8';
      ctx.lineWidth = isExt ? 8 / (mapZoom * 0.7) : 3 / (mapZoom * 0.7);

      if (isExt) {
        ctx.shadowColor = 'rgba(0,0,0,0.1)';
        ctx.shadowBlur = 10 / (mapZoom * 0.7);
      }
      ctx.stroke();
      ctx.shadowBlur = 0; // Reset shadow
    });

    // Draw POIs (Non-exhibits) from JSON
    mockMuseumData.pois.forEach(poi => {
      if (poi.type === 'exhibit') return; // Handled below in tour items

      const cx = tx(poi.position.x);
      const cy = ty(poi.position.y);

      // Match Editor.jsx HTML box styling exactly
      let label = 'EX';
      let bgColor = '#8b5cf6'; // exhibit

      if (poi.type === 'exit') {
        label = poi.subType === 'emergency' ? 'SOS' : 'Exit';
        bgColor = poi.subType === 'emergency' ? '#ef4444' : '#10b981';
      } else if (poi.type === 'restaurant') {
        label = poi.subType === 'bar' ? 'Bar' : poi.subType === 'restaurant-bar' ? 'R&B' : 'Café';
        bgColor = '#f59e0b';
      } else if (poi.type === 'restroom') {
        label = 'WC';
        bgColor = '#0ea5e9';
      }

      ctx.save();
      ctx.shadowColor = 'rgba(0,0,0,0.2)';
      ctx.shadowBlur = 8 / mapZoom;
      ctx.fillStyle = bgColor;
      const boxW = 38 / (mapZoom * 0.8);
      const boxH = 22 / (mapZoom * 0.8);
      ctx.beginPath();
      ctx.roundRect(cx - boxW / 2, cy - boxH / 2, boxW, boxH, 6 / (mapZoom * 0.8));
      ctx.fill();
      ctx.restore();

      ctx.fillStyle = 'white';
      ctx.font = `bold ${10 / (mapZoom * 0.8)}px sans-serif`;
      ctx.textBaseline = 'middle';
      ctx.textAlign = 'center';
      ctx.fillText(label.toUpperCase(), cx, cy);
    });

    // Draw current routing path
    if (currentPath.length > 0) {
      ctx.beginPath();
      ctx.moveTo(userPos.x, userPos.y);
      currentPath.forEach((pt) => ctx.lineTo(pt.x, pt.y));
      ctx.strokeStyle = '#3b82f6';
      ctx.lineWidth = 5 / (mapZoom * 0.7);
      ctx.setLineDash([12 / (mapZoom * 0.7), 8 / (mapZoom * 0.7)]);
      ctx.globalAlpha = 0.5;
      ctx.stroke();
      ctx.globalAlpha = 1.0;
      ctx.setLineDash([]);
    }

    // Draw active Tour Items (Exhibits)
    items.forEach((item, index) => {
      const isActive = index === currentIndex;
      ctx.beginPath();
      ctx.arc(item.x, item.y, 10 / (mapZoom * 0.8), 0, 2 * Math.PI);

      const grad = ctx.createRadialGradient(item.x, item.y, 0, item.x, item.y, 10 / (mapZoom * 0.8));
      grad.addColorStop(0, isActive ? '#f87171' : '#cbd5e1');
      grad.addColorStop(1, isActive ? '#ef4444' : '#94a3b8');

      ctx.fillStyle = grad;
      ctx.fill();

      if (isActive) {
        ctx.beginPath();
        ctx.arc(item.x, item.y, 18 / (mapZoom * 0.8), 0, 2 * Math.PI);
        ctx.strokeStyle = 'rgba(239, 68, 68, 0.3)';
        ctx.lineWidth = 4 / (mapZoom * 0.8);
        ctx.stroke();
      }
    });

    // Draw User Location
    ctx.save();
    ctx.shadowColor = 'rgba(59, 130, 246, 0.5)';
    ctx.shadowBlur = 15 / mapZoom;

    // Outer pulse ring
    ctx.beginPath();
    ctx.arc(userPos.x, userPos.y, 14 / (mapZoom * 0.8), 0, 2 * Math.PI);
    ctx.fillStyle = 'rgba(59, 130, 246, 0.2)';
    ctx.fill();

    // Inner core
    ctx.beginPath();
    ctx.arc(userPos.x, userPos.y, 9 / (mapZoom * 0.8), 0, 2 * Math.PI);
    ctx.fillStyle = '#3b82f6';
    ctx.fill();
    ctx.strokeStyle = '#fff';
    ctx.lineWidth = 2.5 / (mapZoom * 0.8);
    ctx.stroke();
    ctx.restore();

    ctx.restore(); // Undo camera transforms

  }, [currentIndex, items, userPos, cameraPos, mapZoom, isTrackingUser, windowSize]);

  // Proximity Auto-Trigger Pop-up
  useEffect(() => {
    if (currentItem && !hasTriggeredCurrent) {
      const dx = userPos.x - currentItem.x;
      const dy = userPos.y - currentItem.y;
      const distance = Math.sqrt(dx * dx + dy * dy);
      if (distance < 20) {
        // Fire the ItemDescription component overlay Pop-Up
        setShowPopup(true);
        setHasTriggeredCurrent(true);
      }
    }
  }, [userPos, currentItem, hasTriggeredCurrent]);

  // Reset auto-trigger when moving to next item
  useEffect(() => {
    setHasTriggeredCurrent(false);
    setShowPopup(false); // Hide popup (proximity-based, independent from bottom bar)
  }, [currentIndex]);

  // Synchronize audio playback with isPlaying state
  useEffect(() => {
    if (isPlaying && currentItem) {
      speak(currentItem.desc, currentItem.id);
    } else {
      pause();
    }
  }, [isPlaying, currentItem, speak, pause]);

  // Sync internal UI isPlaying with actual audio playback state
  useEffect(() => {
    // Allows the Play button to reset when the audio stops naturally
    setIsPlaying(isSpeaking);
  }, [isSpeaking]);

  // Controller Logic
  const moveUser = (dx, dy) => {
    setUserPos(prev => {
      const step = 4;
      // Convert abstract direction to dynamic relative size (optional: could stay static 4px)
      const nx = prev.x + dx * step;
      const ny = prev.y + dy * step;


      if (!collisionGrid) return prev;

      const c = Math.floor(nx / collisionGrid.gridSize);
      const r = Math.floor(ny / collisionGrid.gridSize);

      if (c >= 0 && c < collisionGrid.cols && r >= 0 && r < collisionGrid.rows && collisionGrid.grid[r][c] === 0) {
        return { x: nx, y: ny };
      }
      return prev;
    });
  };

  const startMove = (dx, dy) => {
    if (moveIntervalRef.current) clearInterval(moveIntervalRef.current);
    setIsPlaying(false);
    setIsTrackingUser(true); // Snap camera back to user when moving!
    moveUser(dx, dy);
    moveIntervalRef.current = setInterval(() => moveUser(dx, dy), 50);
  };

  const stopMove = () => {
    if (moveIntervalRef.current) {
      clearInterval(moveIntervalRef.current);
      moveIntervalRef.current = null;
    }
  };

  // Canvas Panning Controls
  const handlePointerDown = (e) => {
    e.preventDefault();
    setIsPanning(true);
    // Unbind camera from user dot on touch layout
    if (isTrackingUser) {
      setIsTrackingUser(false);
      setCameraPos(userPos);
    }
    lastPanRef.current = { x: e.clientX, y: e.clientY };
  };

  const handlePointerMove = (e) => {
    if (!isPanning) return;
    const dx = e.clientX - lastPanRef.current.x;
    const dy = e.clientY - lastPanRef.current.y;
    lastPanRef.current = { x: e.clientX, y: e.clientY };

    // Move camera relative to zoom factor
    // Loosen clamps to allow freer exploration of the large map
    setCameraPos(prev => ({
      x: prev.x - dx / mapZoom,
      y: prev.y - dy / mapZoom
    }));
  };

  const handlePointerUp = () => {
    setIsPanning(false);
  };

  const handleNext = () => {
    if (currentIndex < items.length - 1) {
      setCurrentIndex(prev => prev + 1);
      setIsPlaying(false);
    }
  };

  const handlePrev = () => {
    if (currentIndex > 0) {
      setCurrentIndex(prev => prev - 1);
      setIsPlaying(false);
    }
  };

  const togglePlay = () => {
    setIsPlaying(!isPlaying);
  };

  const handleMicRequest = async () => {
    try {
      // simulate recording and request
      setAiResponse("Listening...");
      const response = await fetch(`/api/AI/musem/${state?.visitId || 'default'}`);
      const data = await response.json();
      setAiResponse(data.message || "Something went wrong.");
    } catch (error) {
      console.error("AI Mic request failed.", error);
      setAiResponse("AI not available currently.");
    }
  };

  const handleCameraScan = () => {
    setIsCameraActive(true);
  };

  return (
    <div className="navigator-container">
      <div className="navigator-header">
        <button className="back-btn" onClick={() => navigate(-1)}>
          <ArrowLeft size={24} />
        </button>
        <h2>{state?.museum || 'Museum Tour'}</h2>
        <div style={{ width: 24 }}></div> {/* spacer */}
      </div>

      <div className="map-view-area">
        <div className="map-instructions">
          Target: <strong>{currentItem.name}</strong>
        </div>

        {/* New utility buttons */}
        <div className="utility-buttons-top">
          <div className="zoom-controls">
            <button className="util-btn zoom-btn" onClick={() => setMapZoom(prev => Math.min(prev + 0.5, 4))} title="Zoom In"><Plus size={20} /></button>
            <button className="util-btn zoom-btn" onClick={() => setMapZoom(prev => Math.max(prev - 0.5, 1))} title="Zoom Out"><Minus size={20} /></button>
          </div>

          <button
            className={`util-btn ${isCameraActive ? 'active' : ''}`}
            onClick={handleCameraScan}
            title="Scan QR Code"
          >
            <Camera size={24} />
          </button>

          <div className="more-menu-wrapper">
            <button
              className="util-btn"
              onClick={() => setShowMoreMenu(!showMoreMenu)}
              title="More Options"
            >
              {showMoreMenu ? <X size={24} /> : <MoreVertical size={24} />}
            </button>

            {showMoreMenu && (
              <div className="more-menu slide-in-top">
                <button className="menu-item" title="Find Toliet">
                  <ToiletIcon size={20} /> Toilet
                </button>
                <button className="menu-item" title="Find Restaurant">
                  <RestaurantIcon size={20} /> Restaurant
                </button>
              </div>
            )}
          </div>
        </div>

        {aiResponse && (
          <div className="ai-feedback fade-in">
            <span>{aiResponse}</span>
            <button onClick={() => setAiResponse(null)}><X size={14} /></button>
          </div>
        )}

        <canvas
          ref={canvasRef}
          width={windowSize.w}
          height={windowSize.h}
          className="indoor-canvas"
          onPointerDown={handlePointerDown}
          onPointerMove={handlePointerMove}
          onPointerUp={handlePointerUp}
          onPointerLeave={handlePointerUp}
        />

        {isCameraActive && (
          <QRScanner
            onScanSuccess={(decodedText) => {
              setIsCameraActive(false);
              alert(`QR Scan result: ${decodedText}`);
            }}
            onScanError={(err) => {
              console.error("QR Scan failed.", err);
              setIsCameraActive(false);
              alert("Camera unavailable or scan failed.");
            }}
            onClose={() => setIsCameraActive(false)}
          />
        )}

        {/* New utility buttons */}
        <div className="utility-buttons-top">
          {!isTrackingUser && (
            <button
              className="util-btn recenter-btn slide-in-top"
              onClick={() => setIsTrackingUser(true)}
              title="Recenter Camera"
            >
              <LocateFixed size={24} color="#3b82f6" />
            </button>
          )}

          <div className="zoom-controls">
            <button className="util-btn zoom-btn" onClick={() => setMapZoom(prev => Math.min(prev + 0.5, 6))} title="Zoom In"><Plus size={20} /></button>
            <button className="util-btn zoom-btn" onClick={() => setMapZoom(prev => Math.max(prev - 0.5, 1))} title="Zoom Out"><Minus size={20} /></button>
          </div>

          <button
            className={`util-btn ${isCameraActive ? 'active' : ''}`}
            onClick={handleCameraScan}
            title="Scan QR Code"
          >
            <Camera size={24} />
          </button>

          <div className="more-menu-wrapper">
            <button
              className="util-btn"
              onClick={() => setShowMoreMenu(!showMoreMenu)}
              title="More Options"
            >
              {showMoreMenu ? <X size={24} /> : <MoreVertical size={24} />}
            </button>

            {showMoreMenu && (
              <div className="more-menu slide-in-top">
                <button className="menu-item" title="Find Toliet">
                  <ToiletIcon size={20} /> Toilet
                </button>
                <button className="menu-item" title="Find Restaurant">
                  <RestaurantIcon size={20} /> Restaurant
                </button>
              </div>
            )}
          </div>
        </div>

        {/* D-Pad Controller for manual touring */}
        <div className="dpad-controller">
          <div className="dpad-row">
            <button onPointerDown={() => startMove(0, -1)} onPointerUp={stopMove} onPointerLeave={stopMove} onContextMenu={(e) => e.preventDefault()} className="dpad-btn up"><ChevronUp size={28} /></button>
          </div>
          <div className="dpad-row middle">
            <button onPointerDown={() => startMove(-1, 0)} onPointerUp={stopMove} onPointerLeave={stopMove} onContextMenu={(e) => e.preventDefault()} className="dpad-btn left"><ChevronLeft size={28} /></button>
            <div className="dpad-center"></div>
            <button onPointerDown={() => startMove(1, 0)} onPointerUp={stopMove} onPointerLeave={stopMove} onContextMenu={(e) => e.preventDefault()} className="dpad-btn right"><ChevronRight size={28} /></button>
          </div>
          <div className="dpad-row">
            <button onPointerDown={() => startMove(0, 1)} onPointerUp={stopMove} onPointerLeave={stopMove} onContextMenu={(e) => e.preventDefault()} className="dpad-btn down"><ChevronDown size={28} /></button>
          </div>
        </div>
      </div>

      {showPopup && (
        <ItemDescription
          item={currentItem}
          onPlayPause={togglePlay}
          isPlaying={isPlaying}
          onClose={() => setShowPopup(false)}
          currentTime={currentTime}
          duration={duration}
          onSeek={seek}
        />
      )}

      <BottomBar
        onPrev={handlePrev}
        onNext={handleNext}
        onPlayPause={togglePlay}
        onMic={handleMicRequest}
        onEasier={() => alert("Finding easier route...")}
        isPlaying={isPlaying}
        hasPrev={currentIndex > 0}
        hasNext={currentIndex < items.length - 1}
        progress={((currentIndex + 1) / items.length) * 100}
        showDescription={showDescription}
        setShowDescription={setShowDescription}
        currentItem={currentItem}
      />
    </div>
  );
}
